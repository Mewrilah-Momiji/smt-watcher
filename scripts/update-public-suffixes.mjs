// Writes src/data/publicSuffixes.ts from the ICANN part of the Public Suffix List.
// Usage: node scripts/update-public-suffixes.mjs [path to public_suffix_list.dat]
// Without a path it fetches https://publicsuffix.org/list/public_suffix_list.dat.
import { readFileSync, writeFileSync } from 'node:fs';
import { domainToASCII } from 'node:url';

const SOURCE = 'https://publicsuffix.org/list/public_suffix_list.dat';
const path = process.argv[2];
const text = path ? readFileSync(path, 'utf8') : await (await fetch(SOURCE)).text();
const icann = text.split('// ===BEGIN ICANN DOMAINS===')[1]?.split('// ===END ICANN DOMAINS===')[0];
if (!icann) throw new Error('No ICANN section found');

const rules = new Set();
const wildcards = new Set();
const exceptions = new Set();
for (const line of icann.split(/\r?\n/)) {
  const rule = line.trim().split(/\s/)[0];
  if (!rule || rule.startsWith('//')) continue;
  // Domains can reach the page as Unicode or as punycode, so both forms are kept.
  const forms = (value) => [...new Set([value, domainToASCII(value)])].filter(Boolean);
  if (rule.startsWith('!')) forms(rule.slice(1)).forEach((form) => exceptions.add(form));
  else if (rule.startsWith('*.')) forms(rule.slice(2)).forEach((form) => wildcards.add(form));
  // A single label such as "de" needs no entry, as the last label is the suffix by default.
  else if (rule.includes('.')) forms(rule).forEach((form) => rules.add(form));
}

// Grouped by top-level domain, which keeps the file small: { uk: 'ac co gov ...' }.
const byTld = {};
for (const rule of [...rules].sort()) {
  const dot = rule.lastIndexOf('.');
  (byTld[rule.slice(dot + 1)] ??= []).push(rule.slice(0, dot));
}
const entries = Object.entries(byTld)
  .sort(([a], [b]) => (a < b ? -1 : 1))
  .map(([tld, heads]) => `  ${JSON.stringify(tld)}: ${JSON.stringify(heads.join(' '))},`)
  .join('\n');

const date = new Date().toISOString().slice(0, 10);
writeFileSync(
  new URL('../src/data/publicSuffixes.ts', import.meta.url),
  `// Generated by scripts/update-public-suffixes.mjs on ${date}. Do not edit by hand.
// Source: the ICANN section of the Public Suffix List, ${SOURCE}
// This Source Code Form is subject to the terms of the Mozilla Public License, v. 2.0.
// If a copy of the MPL was not distributed with this file, You can obtain one at https://mozilla.org/MPL/2.0/.

/** Suffixes of two or more labels, grouped by top-level domain: the labels before it, separated by spaces. */
export const SUFFIXES_BY_TLD: Record<string, string> = {
${entries}
};

/** Under these, every name is a suffix of its own, such as anything.ck. */
export const WILDCARD_SUFFIXES: string[] = ${JSON.stringify([...wildcards].sort())};

/** Exceptions to the wildcards, which are registrable domains themselves, such as www.ck. */
export const EXCEPTION_DOMAINS: string[] = ${JSON.stringify([...exceptions].sort())};
`,
);
console.log(`rules ${rules.size}, wildcards ${wildcards.size}, exceptions ${exceptions.size}`);
