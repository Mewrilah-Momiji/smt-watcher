import type { Lang } from '../i18n';

export type ReportCase = 'advertising' | 'illegal-content' | 'phishing';

export type ReportLanguage = 'de' | 'en' | 'fr' | 'it' | 'nl' | 'pl' | 'da' | 'cs' | 'sk' | 'hu' | 'sl' | 'sv' | 'fi' | 'es' | 'pt' | 'nb' | 'bg' | 'ro' | 'el' | 'et' | 'lv' | 'lt' | 'hr' | 'pt-BR' | 'ja' | 'ko';

export type ReportingChannel =
  | { type: 'form'; url: string }
  | { type: 'email'; address: string };

/** English and German are always there. A body without its own text in another language shows the English one. */
type Localized<T> = Record<'en' | 'de', T> & Partial<Record<Lang, T>>;

export function localized<T>(value: Localized<T>, lang: Lang): T {
  return value[lang] ?? value.en;
}

export interface ReportingBody {
  id: string;
  name: string;
  /** How the body is named in English reports to foreign providers. */
  internationalName: string;
  /** Limit for a file upload that needs an .eml file, if the body offers one. */
  emlUploadLimitBytes?: number;
  purpose: Localized<string>;
  channel: ReportingChannel;
  language: ReportLanguage;
  /** Cases this body accepts. */
  cases: ReportCase[];
  /** The body only acts if the email advertises a phone number. */
  requiresPhone: boolean;
  /** The body asks for the original headers in the report. */
  wantsHeaders: boolean;
  /** How to submit the report. */
  instructions: Localized<string>;
  /** What to expect from this body, shown before sending. */
  notices: Localized<string[]>;
  source: string;
  checkedAt: string;
}

export interface CountryData {
  code: string;
  /** The language of reports to bodies in this country. */
  language: ReportLanguage;
  bodies: ReportingBody[];
  /** Cases with no checked body yet. They are shown as "not checked". */
  uncheckedCases: ReportCase[];
  /** What is known for an unchecked case, such as a body that takes reports by phone only. */
  uncheckedNotes?: Partial<Record<ReportCase, Localized<string>>>;
}

