/** The region in the browser language picks the country, then the language alone. Everyone else starts with Germany, the first one checked. */
export function defaultCountry(language: string): CountryData {
  const [base, region] = language.toLowerCase().split('-');
  const checked = COUNTRIES.filter((country) => country.code !== OTHER_COUNTRY);
  // Some languages have codes that differ from their country codes.
  const country = { da: 'dk', cs: 'cz', sl: 'si', sv: 'se', nb: 'no', nn: 'no', el: 'gr', et: 'ee', ja: 'jp', ko: 'kr' }[base] ?? base;
  return (
    checked.find((entry) => entry.code.toLowerCase() === region) ??
    checked.find((entry) => entry.code.toLowerCase() === country) ??
    COUNTRIES[0]
  );
}
